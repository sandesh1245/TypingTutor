        public PassageLanguage Language { get; set; } = PassageLanguage.English;
        public List<FallingWord> ActiveWords { get; private set; } = new List<FallingWord>();
        public int Score { get; private set; }
        public int HighScore { get; private set; }
        public int Health { get; private set; } = 5;
        public int Level { get; private set; } = 1;
        public bool IsGameOver { get; private set; }
        public bool IsRunning { get; private set; }

        public string CurrentInput { get; private set; } = string.Empty;

        private DispatcherTimer? _gameTimer;
        private Random _rnd = new Random();
        private int _spawnCounter = 0;

        public event Action? OnGameTick;
        public event Action? OnGameOver;

        public void SetLanguage(PassageLanguage lang)
        {
            Language = lang;
            if (IsRunning)
            {
                ActiveWords.Clear();
                CurrentInput = string.Empty;
                SpawnWord();
                OnGameTick?.Invoke();
            }
        }

        public void StartNewGame()
        {
            ActiveWords.Clear();
            Score = 0;
            Health = 5;
            Level = 1;
            IsGameOver = false;
            IsRunning = true;
            CurrentInput = string.Empty;

            _gameTimer = new DispatcherTimer
            {
                Interval = TimeSpan.FromMilliseconds(50)
            };
            _gameTimer.Tick += GameLoop;
            _gameTimer.Start();

            SpawnWord();
            OnGameTick?.Invoke();
        }

        private void GameLoop(object? sender, EventArgs e)
        {
            if (!IsRunning || IsGameOver) return;

            _spawnCounter++;
            if (_spawnCounter >= Math.Max(20, 60 - (Level * 5)))
            {
                _spawnCounter = 0;
                SpawnWord();
            }

            for (int i = ActiveWords.Count - 1; i >= 0; i--)
            {
                var word = ActiveWords[i];
                word.Y += word.Speed + (Level * 0.4);

                // Check hit bottom
                if (word.Y >= 430)
                {
                    ActiveWords.RemoveAt(i);
                    Health--;

                    if (Health <= 0)
                    {
                        EndGame();
                        return;
                    }
                }
            }

            OnGameTick?.Invoke();
        }

        private void SpawnWord()
        {
            if (ActiveWords.Count >= 8) return;

            string[] bank = WordBanks.TryGetValue(Language, out var b) ? b : WordBanks[PassageLanguage.English];
            string text = bank[_rnd.Next(bank.Length)];
            double x = _rnd.Next(40, 560);

            ActiveWords.Add(new FallingWord
            {
                Text = text,
                X = x,
                Y = 0,
                Speed = 1.2 + (_rnd.NextDouble() * 1.3)
            });
        }

        public void ProcessTypedInput(string input)
        {
            if (!IsRunning || IsGameOver || string.IsNullOrEmpty(input)) return;

            var comparison = Language == PassageLanguage.English
                ? StringComparison.OrdinalIgnoreCase
                : StringComparison.Ordinal;

            // Check if there is an already targeted word
            var targeted = ActiveWords.FirstOrDefault(w => w.IsTargeted);
            if (targeted != null)
            {
                string candidate = CurrentInput + input;
                if (targeted.Text.StartsWith(candidate, comparison))
                {
                    CurrentInput = candidate;
                    targeted.MatchedChars = CurrentInput.Length;

                    if (CurrentInput.Length >= targeted.Text.Length)
                    {
                        Score += targeted.Text.Length * 15 * Level;
                        if (Score > HighScore) HighScore = Score;
                        if (Score > Level * 300) Level++;

                        ActiveWords.Remove(targeted);
                        CurrentInput = string.Empty;
                    }

                    OnGameTick?.Invoke();
                }
            }
            else
            {
                // Find first falling word matching the input
                var match = ActiveWords.FirstOrDefault(w => w.Text.StartsWith(input, comparison));
                if (match != null)
                {
                    foreach (var w in ActiveWords) w.IsTargeted = false;
                    match.IsTargeted = true;
                    CurrentInput = input;
                    match.MatchedChars = CurrentInput.Length;

                    if (CurrentInput.Length >= match.Text.Length)
                    {
                        Score += match.Text.Length * 15 * Level;
                        if (Score > HighScore) HighScore = Score;
                        if (Score > Level * 300) Level++;

                        ActiveWords.Remove(match);
                        CurrentInput = string.Empty;
                    }

                    OnGameTick?.Invoke();
                }
            }
        }

        public void ProcessTypedKey(char ch)
        {
            ProcessTypedInput(ch.ToString());
        }

        public void HandleBackspace()
        {
            if (!IsRunning || IsGameOver || string.IsNullOrEmpty(CurrentInput)) return;

            CurrentInput = CurrentInput.Substring(0, CurrentInput.Length - 1);
            var targeted = ActiveWords.FirstOrDefault(w => w.IsTargeted);
            if (targeted != null)
            {
                targeted.MatchedChars = CurrentInput.Length;
                if (CurrentInput.Length == 0)
                {
                    targeted.IsTargeted = false;
                }
            }

            OnGameTick?.Invoke();
        }

        public void ClearBuffer()
        {
            CurrentInput = string.Empty;
            foreach (var w in ActiveWords)
            {
                w.IsTargeted = false;
                w.MatchedChars = 0;
            }
            OnGameTick?.Invoke();
        }

        private void EndGame()
        {
            IsGameOver = true;
            IsRunning = false;
            _gameTimer?.Stop();
            OnGameOver?.Invoke();
            OnGameTick?.Invoke();
        }

        public void Stop()
        {
            IsRunning = false;
            _gameTimer?.Stop();
        }
    }
